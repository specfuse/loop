"""Enforce `gen-contract.yml`: the machine-checkable half of a component repo's
generated-code bar (specfuse/loop#3536).

A component repo receives generated code from its spec repo. Its contract file
states what that code must look like and what nobody may do to it. Every
finding carries a rule ID, a file, a line and the rule's `why`, so an agent can
act on one without a conversation, and two runs over the same tree produce the
same set.

    specfuse gen-contract                      # every rule
    specfuse gen-contract --only GEN-001 GEN-004
    specfuse gen-contract --explain GEN-004
    specfuse gen-contract --list
    specfuse gen-contract --json findings.json

Exit codes:
    0  no `error` findings (warnings may still be printed)
    1  at least one `error` finding
    2  the checker could not run (bad contract, unknown builtin, not a git repo)

Ownership (specfuse/authoring#171): the RULES and any project-specific checks
belong to the component repo; this module is the shared engine. Wire it as a
`code` gate in `.specfuse/verification.yml`.

## The contract file

    version: 1
    builtins: scripts/gen_contract_checks.py   # optional: project-specific checks
    filesets:
      generated:
        include: ["**/gen-src/**/*.cs"]
        exclude: ["**/obj/**"]
    rules:
      - id: GEN-001
        title: Generated files carry the auto-generated header
        check: first_line_equals
        scope: generated            # a fileset name, or an inline {include, exclude}
        value: "// <auto-generated/>"
        doc: docs/generated-code-expectations.md#headers
        why: >
          Tools key off the header to skip analysis; a file without it is
          linted and "fixed" by hand, then overwritten by the next regen.

Generic checks (`check:`):

  forbid_pattern      `pattern` must not match any line (`exclude_lines` exempts lines)
  require_pattern     every file must match each of `patterns`
  first_line_equals   the first line is exactly `value`
  first_line_in       the first line is one of `values`
  filename_matches    each file's name matches `pattern`
  forbid_paths        no path matches `pattern` unless it contains `unless_path`
  ratchet             each of `counters` ({name, scope, pattern, max, unit: files|matches})
                      stays at or under `max`; `max` only ever goes down
  builtin             `name:` a function in the `builtins:` module

Every content check also takes `only_files_matching` / `exclude_files_matching`,
regexes over the file's base name.

A builtin has the signature `fn(root, rule, scope, filesets, files) -> list[Finding]`
and may import `Finding`, `read`, `filtered` and `Scope` from this module. The
module's `BUILTINS` dict, when present, maps names to functions; otherwise the
name is looked up as a module attribute.

Safety, on purpose:

  * Files come from `git ls-files`, so untracked build output is never judged.
    A tracked path missing from disk (deleted by a regen, not yet staged) is
    skipped, not judged as empty.
  * A rule whose scope matches no file FAILS. A selector that silently matches
    nothing is a rule that silently checks nothing. `allow_empty: true` opts out,
    for a rule written ahead of the surface it guards. `forbid_paths` is exempt:
    its scope names what must not exist, so empty is its pass state.
  * `waived_until: {max, until, reason}` freezes a backlog. More sites than
    `max` fail, `max` or fewer warn, and zero sites FAIL until the block is
    deleted, so a satisfied waiver can't linger and hide the next regression.
  * The contract is validated before anything runs: known checks, unique IDs,
    known filesets, regexes that compile. A broken contract is exit 2, never a
    green run.

YAML: the loop takes no runtime dependencies, so the file is read with the
loop's strict `_miniyaml` after a pre-pass (`normalize_yaml`) that rewrites the
two YAML features every real contract uses, folded block scalars (`>`) for
prose and single-quoted strings for regexes, into double-quoted strings.
Anchors, aliases and flow mappings stay unsupported: use `filesets:`.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Callable

from . import _miniyaml

CONTRACT_DEFAULT = "gen-contract.yml"
EXIT_OK, EXIT_FINDINGS, EXIT_BROKEN = 0, 1, 2
SEVERITIES = ("error", "warn")


class ContractError(Exception):
    """The contract or the repository can't be checked: exit 2."""


# --------------------------------------------------------------------------- #
# YAML pre-pass                                                               #
# --------------------------------------------------------------------------- #

_BLOCK_HEADER = re.compile(r"^(\s*(?:- )?)([A-Za-z_][A-Za-z0-9_-]*):\s+([>|])([+-]?)\s*(?:#.*)?$")
_VALUE_START = re.compile(r"^(\s*(?:- )?(?:[A-Za-z_][A-Za-z0-9_-]*:\s+)?)(.*)$")


def _dq(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _requote(value: str, lineno: int) -> str:
    """Rewrite every single-quoted string in a value as a double-quoted one.

    Walks the value once, leaving double-quoted strings untouched, so a `'`
    inside `"..."` stays literal and a `"` inside `'...'` gets escaped.
    YAML's `''` escape inside single quotes becomes one `'`.
    """
    out, i, n = [], 0, len(value)
    while i < n:
        c = value[i]
        if c == '"':
            j = i + 1
            while j < n and value[j] != '"':
                j += 2 if value[j] == "\\" else 1
            out.append(value[i:j + 1])
            i = j + 1
        elif c == "'" and (i == 0 or value[i - 1] in " [,"):
            j, buf = i + 1, []
            while True:
                if j >= n:
                    raise ContractError(f"line {lineno}: unterminated single-quoted string")
                if value[j] == "'":
                    if j + 1 < n and value[j + 1] == "'":
                        buf.append("'")
                        j += 2
                        continue
                    break
                buf.append(value[j])
                j += 1
            out.append(_dq("".join(buf)))
            i = j + 1
        elif c == "#" and (i == 0 or value[i - 1] in " \t"):
            break  # trailing comment: nothing after it is a value
        else:
            out.append(c)
            i += 1
    return "".join(out).rstrip()


def normalize_yaml(text: str) -> str:
    """Rewrite folded/literal block scalars and single-quoted strings as
    double-quoted strings the strict `_miniyaml` subset accepts.

    Block scalars are folded to one line: `_miniyaml`'s double-quoted strings
    carry no newline escape, and every block scalar in a contract is prose
    (`doc`, `why`, `reason`) that the engine prints whitespace-normalized
    anyway. A regex that needs a newline belongs on one line with `\\n`.
    """
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m = _BLOCK_HEADER.match(line)
        if m:
            prefix, key = m.group(1), m.group(2)
            key_indent = len(prefix)
            body: list[str] = []
            i += 1
            while i < len(lines) and (
                not lines[i].strip() or len(lines[i]) - len(lines[i].lstrip(" ")) > key_indent
            ):
                body.append(lines[i].strip())
                i += 1
            out.append(f"{prefix}{key}: {_dq(' '.join(p for p in body if p))}")
            continue
        stripped = line.lstrip(" ")
        if "'" in line and not stripped.startswith("#"):
            vm = _VALUE_START.match(line)
            line = vm.group(1) + _requote(vm.group(2), i + 1)
        out.append(line)
        i += 1
    return "\n".join(out) + "\n"


def load_contract(path: Path) -> dict:
    if not path.is_file():
        raise ContractError(f"{path}: no contract file")
    try:
        data = _miniyaml.parse(normalize_yaml(path.read_text(encoding="utf-8")))
    except _miniyaml.MiniYAMLError as exc:
        raise ContractError(f"{path.name}: {exc}") from exc
    if not isinstance(data, dict):
        raise ContractError(f"{path.name}: expected a mapping at the top level")
    if data.get("version") != 1:
        raise ContractError(f"{path.name}: `version: 1` is required")
    if not isinstance(data.get("rules"), list) or not data["rules"]:
        raise ContractError(f"{path.name}: `rules:` must be a non-empty list")
    return data


