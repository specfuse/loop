# Generic checks                                                              #
# --------------------------------------------------------------------------- #


def check_filename_matches(root, rule, scope, _fs, _files):
    r = re.compile(rule["pattern"])
    return [Finding(rule["id"], rule["severity"], p, 0, f"file name does not match {rule['pattern']!r}")
            for p in filtered(scope.paths, rule) if not r.search(Path(p).name)]


def check_first_line_equals(root, rule, scope, _fs, _files):
    want = str(rule["value"])
    out = []
    for p in filtered(scope.paths, rule):
        first = read(root, p).split("\n", 1)[0].strip()
        if first != want:
            out.append(Finding(rule["id"], rule["severity"], p, 1,
                               f"first line is {first!r}, expected {want!r}"))
    return out


def check_first_line_in(root, rule, scope, _fs, _files):
    """For a surface emitted by more than one template family. Listing the
    accepted headers is the point: a third one fails."""
    want = [str(v) for v in rule["values"]]
    out = []
    for p in filtered(scope.paths, rule):
        first = read(root, p).split("\n", 1)[0].strip()
        if first not in want:
            out.append(Finding(rule["id"], rule["severity"], p, 1,
                               f"first line is {first!r}, expected one of "
                               + " | ".join(repr(v) for v in want)))
    return out


def check_require_pattern(root, rule, scope, _fs, _files):
    pats = [(s, re.compile(s, re.M)) for s in _as_list(rule["patterns"])]
    out = []
    for p in filtered(scope.paths, rule):
        text = read(root, p)
        out.extend(Finding(rule["id"], rule["severity"], p, 0, f"missing required pattern {src!r}")
                   for src, r in pats if not r.search(text))
    return out


def check_forbid_pattern(root, rule, scope, _fs, _files):
    r = re.compile(rule["pattern"])
    skip = re.compile(rule["exclude_lines"]) if rule.get("exclude_lines") else None
    out = []
    for p in filtered(scope.paths, rule):
        for n, line in enumerate(read(root, p).split("\n"), 1):
            if r.search(line) and not (skip and skip.search(line)):
                out.append(Finding(rule["id"], rule["severity"], p, n, f"forbidden: {line.strip()[:120]}"))
    return out


def check_forbid_paths(root, rule, scope, _fs, _files):
    r = re.compile(rule["pattern"])
    unless = rule.get("unless_path")
    why = f" but is not under {unless!r}" if unless else ""
    return [Finding(rule["id"], rule["severity"], p, 0, f"path matches {rule['pattern']!r}{why}")
            for p in scope.paths if r.search(p) and not (unless and unless in p)]


def check_ratchet(root, rule, _scope, filesets, files):
    out = []
    for c in rule["counters"]:
        sc = Scope(c["scope"], filesets, files)
        r = re.compile(c["pattern"], re.M)
        if c.get("unit", "files") == "files":
            n = sum(1 for p in sc.paths if r.search(read(root, p)))
        else:
            n = sum(len(r.findall(read(root, p))) for p in sc.paths)
        if n > c["max"]:
            out.append(Finding(rule["id"], rule["severity"], CONTRACT_DEFAULT, 0,
                               f"ratchet `{c['name']}` at {n}, max {c['max']} ({n - c['max']} over). "
                               "Fix the new occurrence; the max only ever goes down."))
        elif n < c["max"]:
            out.append(Finding(rule["id"], "info", CONTRACT_DEFAULT, 0,
                               f"ratchet `{c['name']}` at {n}, max {c['max']}: "
                               f"lower the max to {n} to lock the gain in."))
    return out


CHECKS: dict[str, Callable] = {
    "filename_matches": check_filename_matches,
    "first_line_equals": check_first_line_equals,
    "first_line_in": check_first_line_in,
    "require_pattern": check_require_pattern,
    "forbid_pattern": check_forbid_pattern,
    "forbid_paths": check_forbid_paths,
    "ratchet": check_ratchet,
}

# Keys each generic check reads, so a typo'd or missing field is caught on load.
_REQUIRED = {
    "filename_matches": ("pattern",),
    "first_line_equals": ("value",),
    "first_line_in": ("values",),
    "require_pattern": ("patterns",),
    "forbid_pattern": ("pattern",),
    "forbid_paths": ("pattern",),
    "ratchet": ("counters",),
    "builtin": ("name",),
}
_REGEX_KEYS = ("pattern", "exclude_lines", "only_files_matching", "exclude_files_matching")


# --------------------------------------------------------------------------- #
# Contract validation and project builtins                                    #
# --------------------------------------------------------------------------- #


def load_builtins(root: Path, contract: dict) -> dict[str, Callable]:
    rel = contract.get("builtins")
    if not rel:
        return {}
    path = root / rel
    if not path.is_file():
        raise ContractError(f"builtins module {rel} not found")
    spec = importlib.util.spec_from_file_location("gen_contract_builtins", path)
    module = importlib.util.module_from_spec(spec)
    # Registered before it runs: `@dataclass` and friends look their module up
    # in sys.modules while the module body is still executing.
    sys.modules[spec.name] = module
    try:
        spec.loader.exec_module(module)
    except Exception as exc:  # noqa: BLE001 - any import failure is a broken contract
        sys.modules.pop(spec.name, None)
        raise ContractError(f"builtins module {rel} failed to import: {exc}") from exc
    table = getattr(module, "BUILTINS", None)
    if isinstance(table, dict):
        return dict(table)
    return {k: v for k, v in vars(module).items() if callable(v) and not k.startswith("_")}


def validate(contract: dict, builtins: dict[str, Callable]) -> None:
    filesets = contract.get("filesets") or {}
    if not isinstance(filesets, dict):
        raise ContractError("`filesets:` must be a mapping of name -> {include, exclude}")
    seen: set[str] = set()
    for idx, rule in enumerate(contract["rules"], 1):
        if not isinstance(rule, dict):
            raise ContractError(f"rule #{idx}: expected a mapping")
        rid = rule.get("id")
        if not rid:
            raise ContractError(f"rule #{idx}: missing `id`")
        if rid in seen:
            raise ContractError(f"{rid}: duplicate rule id")
        seen.add(rid)
        for key in ("title", "check", "why"):
            if not rule.get(key):
                raise ContractError(f"{rid}: missing `{key}`")
        rule.setdefault("severity", "error")
        if rule["severity"] not in SEVERITIES:
            raise ContractError(f"{rid}: severity must be one of {', '.join(SEVERITIES)}")
        kind = rule["check"]
        if kind != "builtin" and kind not in CHECKS:
            raise ContractError(f"{rid}: unknown check {kind!r} (known: {', '.join(sorted(CHECKS))}, builtin)")
        for key in _REQUIRED[kind]:
            if rule.get(key) in (None, "", []):
                raise ContractError(f"{rid}: check `{kind}` needs `{key}`")
        if kind == "builtin" and rule["name"] not in builtins:
            raise ContractError(f"{rid}: unknown builtin {rule['name']!r}"
                                + ("" if contract.get("builtins") else " (no `builtins:` module declared)"))
        if kind not in ("ratchet", "builtin") and "scope" not in rule:
            raise ContractError(f"{rid}: missing `scope`")
        if isinstance(rule.get("scope"), str) and rule["scope"] not in filesets:
            raise ContractError(f"{rid}: unknown fileset `{rule['scope']}`")
        for key in _REGEX_KEYS:
            if rule.get(key):
                try:
                    re.compile(rule[key])
                except re.error as exc:
                    raise ContractError(f"{rid}: `{key}` is not a valid regex: {exc}") from exc
        for c in rule.get("counters") or []:
            for key in ("name", "scope", "pattern", "max"):
                if c.get(key) in (None, ""):
                    raise ContractError(f"{rid}: every ratchet counter needs `{key}`")
        w = rule.get("waived_until")
        if w is not None and (not isinstance(w, dict) or not isinstance(w.get("max"), int) or not w.get("until")):
            raise ContractError(f"{rid}: `waived_until` needs an integer `max` and an `until`")


# --------------------------------------------------------------------------- #
# Driver                                                                      #
# --------------------------------------------------------------------------- #


def apply_waiver(rule: dict, findings: list[Finding]) -> list[Finding]:
    """Collapse a waived rule's findings into one line, capped so it can't grow.

    A waiver isn't a mute. The rule keeps running, the count stays visible, and
    `max` freezes it: a regen that adds a site fails even while the backlog is
    tolerated. At zero the waiver fails until it's deleted, so the rule turns
    hard the moment its backlog is gone rather than whenever someone notices.
    """
    w = rule.get("waived_until")
    if not w:
        return findings
    errors = [f for f in findings if f.severity == "error"]
    rest = [f for f in findings if f.severity != "error"]
    n, rid = len(errors), rule["id"]
    if n > w["max"]:
        return rest + [Finding(rid, "error", CONTRACT_DEFAULT, 0,
                               f"waived at {w['max']} site(s), found {n}: {n - w['max']} more than the "
                               f"frozen backlog. A waiver freezes a backlog; it admits no new sites. To see "
                               f"which: `--only {rid} --json a.json` here and on main, then diff the "
                               f"file:line sets. Waiver ends when: {w['until']}")]
    if n == 0:
        return rest + [Finding(rid, "error", CONTRACT_DEFAULT, 0,
                               f"waiver satisfied, 0 sites remain. Delete the `waived_until:` block on "
                               f"{rid} so the rule is hard.")]
    sample = "; ".join(f"{f.file}:{f.line}" for f in errors[:3])
    return rest + [Finding(rid, "warn", CONTRACT_DEFAULT, 0,
                           f"{n} waived site(s), max {w['max']}, no new ones. e.g. {sample}. "
                           f"Waiver ends when: {w['until']}")]


def run_rule(root: Path, rule: dict, filesets: dict, files: list[str],
             builtins: dict[str, Callable]) -> list[Finding]:
    kind = rule["check"]
    fn = builtins[rule["name"]] if kind == "builtin" else CHECKS[kind]
    scope = Scope(rule["scope"], filesets, files) if "scope" in rule else None
    # `forbid_paths` asserts that its scope holds nothing, so empty is its pass state.
    if scope is not None and not scope.paths and kind != "forbid_paths" and not rule.get("allow_empty"):
        return [Finding(rule["id"], "error", CONTRACT_DEFAULT, 0,
                        "scope matches no tracked file, so this rule checks nothing. Fix the "
                        "scope, or set `allow_empty: true` if it guards a surface that doesn't exist yet.")]
    return apply_waiver(rule, list(fn(root, rule, scope, filesets, files)))


def _one_line(text) -> str:
    return " ".join(str(text or "").split())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="specfuse gen-contract",
        description="Check a component repo's generated code against gen-contract.yml.",
    )
    ap.add_argument("--contract", default=CONTRACT_DEFAULT, help="contract file, repo-relative")
    ap.add_argument("--root", type=Path, help="repository root (default: the enclosing git repo)")
    ap.add_argument("--only", nargs="+", metavar="RULE_ID", help="run only these rules (space or comma separated)")
    ap.add_argument("--explain", metavar="RULE_ID", help="print one rule and why it exists")
    ap.add_argument("--list", action="store_true", help="list the rules")
    ap.add_argument("--json", metavar="PATH", help="also write findings as JSON")
    ap.add_argument("--quiet", action="store_true", help="print findings only, no per-rule progress")
    args = ap.parse_args(argv)

    try:
        return _run(args)
    except ContractError as exc:
        print(f"gen-contract: {exc}", file=sys.stderr)
        return EXIT_BROKEN


def _run(args: argparse.Namespace) -> int:
    root = repo_root(args.root)
    _TEXT.clear()
    contract = load_contract(root / args.contract)
    builtins = load_builtins(root, contract)
    validate(contract, builtins)
    filesets = contract.get("filesets") or {}
    rules = contract["rules"]
    by_id = {r["id"]: r for r in rules}

    if args.explain:
        r = by_id.get(args.explain)
        if not r:
            raise ContractError(f"no rule {args.explain}")
        kind = r["check"] + (f"/{r['name']}" if r["check"] == "builtin" else "")
        print(f"{r['id']}  {r['title']}\n  severity : {r['severity']}\n  doc      : {r.get('doc', '-')}\n"
              f"  check    : {kind}\n  why      : {_one_line(r['why'])}")
        if r.get("waived_until"):
            w = r["waived_until"]
            print(f"  WAIVED   : {w['max']} site(s), frozen {w.get('recorded', '?')}\n"
                  f"  until    : {_one_line(w['until'])}\n  reason   : {_one_line(w.get('reason'))}")
        return EXIT_OK

    if args.list:
        for r in rules:
            print(f"{r['id']}  {r['severity']:<5}  {r['title']}")
        return EXIT_OK

    wanted = {i for chunk in (args.only or []) for i in chunk.split(",") if i}
    unknown = wanted - set(by_id)
    if unknown:
        raise ContractError(f"no rule {', '.join(sorted(unknown))}")
    selected = [r for r in rules if not wanted or r["id"] in wanted]
    files = tracked_files(root)

    findings: list[Finding] = []
    for rule in selected:
        got = run_rule(root, rule, filesets, files, builtins)
        findings.extend(got)
        if not args.quiet:
            errs = [f for f in got if f.severity == "error"]
            warns = [f for f in got if f.severity == "warn"]
            mark = "FAIL" if errs else ("WARN" if warns else "ok  ")
            print(f"  {mark}  {rule['id']}  {rule['title']}" + (f"  ({len(errs)})" if errs else ""))

    errors = [f for f in findings if f.severity == "error"]
    others = [f for f in findings if f.severity != "error"]
    if errors:
        print(f"\n{len(errors)} violation(s):\n")
        for f in errors:
            print(f.render())
        print("\nwhy these matter:")
        for rid in dict.fromkeys(f.rule for f in errors):
            print(f"  {rid}  {_one_line(by_id[rid]['why'])}\n           doc: {by_id[rid].get('doc', '-')}")
    if others and not args.quiet:
        print(f"\n{len(others)} informational:")
        for f in others:
            print("  " + f.render().replace("\n           ", " | "))

    if args.json:
        Path(args.json).write_text(json.dumps({
            "contract": args.contract,
            "rulesRun": [r["id"] for r in selected],
            "errorCount": len(errors),
            "findings": [asdict(f) for f in findings],
        }, indent=2) + "\n", encoding="utf-8")

    if not errors:
        print(f"\ngen-contract: {len(selected)} rule(s) green over {len(files)} tracked file(s)")
    return EXIT_FINDINGS if errors else EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
