# Files, scopes, findings                                                     #
# --------------------------------------------------------------------------- #


@dataclass
class Finding:
    rule: str
    severity: str  # error | warn | info
    file: str
    line: int
    message: str

    def render(self) -> str:
        loc = f"{self.file}:{self.line}" if self.line else self.file
        return f"{self.rule}  {self.severity:<5}  {loc}\n           {self.message}"


def repo_root(start: Path | None = None) -> Path:
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=start,
                         capture_output=True, text=True, check=False)
    if out.returncode != 0:
        raise ContractError("not inside a git repository")
    return Path(out.stdout.strip())


def tracked_files(root: Path) -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, text=True, check=False)
    if out.returncode != 0:
        raise ContractError("git ls-files failed")
    # The index still lists a file deleted in the worktree but not yet staged,
    # the normal state right after a regen drops a model. It has no content to
    # judge; reading it as '' would report violations on a file that is gone.
    return sorted(p for p in out.stdout.split("\0") if p and (root / p).is_file())


def glob_to_re(pattern: str) -> re.Pattern:
    """A path glob as a regex: `**/` any directories, `**` anything, `*` and `?` within a segment."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append(r"(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(r".*")
            i += 2
        elif pattern[i] == "*":
            out.append(r"[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append(r"[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


class Scope:
    """A resolved set of repo-relative paths: a fileset name or an inline {include, exclude}."""

    def __init__(self, spec, filesets: dict, files: list[str]):
        if isinstance(spec, str):
            if spec not in filesets:
                raise ContractError(f"unknown fileset `{spec}`")
            spec = filesets[spec]
        if not isinstance(spec, dict) or not spec.get("include"):
            raise ContractError(f"a scope needs an `include:` list, got {spec!r}")
        inc = [glob_to_re(g) for g in _as_list(spec["include"])]
        exc = [glob_to_re(g) for g in _as_list(spec.get("exclude"))]
        self.paths = [f for f in files
                      if any(r.match(f) for r in inc) and not any(r.match(f) for r in exc)]


def _as_list(v) -> list:
    if v is None:
        return []
    return v if isinstance(v, list) else [v]


_TEXT: dict[str, str] = {}


def read(root: Path, rel: str) -> str:
    """A tracked file's text, read once per run however many rules scan it."""
    key = str(root / rel)
    if key not in _TEXT:
        try:
            _TEXT[key] = (root / rel).read_text(encoding="utf-8", errors="replace")
        except OSError:
            _TEXT[key] = ""
    return _TEXT[key]


def filtered(paths: list[str], rule: dict) -> list[str]:
    """Apply a rule's base-name filters, `only_files_matching` / `exclude_files_matching`."""
    out = paths
    if rule.get("only_files_matching"):
        r = re.compile(rule["only_files_matching"])
        out = [p for p in out if r.search(Path(p).name)]
    if rule.get("exclude_files_matching"):
        r = re.compile(rule["exclude_files_matching"])
        out = [p for p in out if not r.search(Path(p).name)]
    return out


