"""Tests for gen_contract.py (specfuse/loop#3536).

Each test builds a throwaway git repo, writes a contract and a few tracked
files, and runs `main()` against it. The load-bearing cases are the ones that
keep the gate honest: a rule whose scope matches nothing fails instead of
passing vacuously, a satisfied waiver fails until it is deleted, and a broken
contract exits 2 rather than producing a green run.
"""

from __future__ import annotations

import contextlib
import io
import json
import subprocess
import tempfile
import textwrap
import unittest
from pathlib import Path

from specfuse.loop import _miniyaml
from specfuse.loop.gen_contract import (
    EXIT_BROKEN,
    EXIT_FINDINGS,
    EXIT_OK,
    main,
    normalize_yaml,
)


class _Repo:
    def __init__(self, tmp: Path):
        self.root = tmp
        subprocess.run(["git", "init", "-q", str(tmp)], check=True)

    def write(self, rel: str, text: str) -> None:
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(text).lstrip("\n"), encoding="utf-8")
        subprocess.run(["git", "add", rel], cwd=self.root, check=True)

    def run(self, *args: str) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            rc = main(["--root", str(self.root), *args])
        return rc, out.getvalue(), err.getvalue()


class GenContractTestCase(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.repo = _Repo(Path(self._tmp.name))

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def contract(self, rules: str, extra: str = "") -> None:
        self.repo.write("gen-contract.yml", "version: 1\n" + textwrap.dedent(extra) + "rules:\n"
                        + textwrap.indent(textwrap.dedent(rules).strip("\n"), "  ") + "\n")


class NormalizeYamlTest(unittest.TestCase):
    def parse(self, text: str):
        return _miniyaml.parse(normalize_yaml(textwrap.dedent(text)))

    def test_folded_block_scalar_becomes_one_line(self):
        data = self.parse("""
            why: >
              first line
              second line # not a comment inside a block scalar

              next paragraph
            after: 1
            """)
        self.assertEqual(data["why"], "first line second line # not a comment inside a block scalar next paragraph")
        self.assertEqual(data["after"], 1)

    def test_block_scalar_inside_sequence_item(self):
        data = self.parse("""
            rules:
              - id: A
                why: >-
                  wrapped
                  prose
              - id: B
            """)
        self.assertEqual([r["id"] for r in data["rules"]], ["A", "B"])
        self.assertEqual(data["rules"][0]["why"], "wrapped prose")

    def test_single_quoted_regex_keeps_backslashes_and_quotes(self):
        data = self.parse(r"""
            pattern: '\bColor\(0x[0-9a-f]{6}\)|"x"|it''s # not a comment'
            """)
        self.assertEqual(data["pattern"], r"""\bColor\(0x[0-9a-f]{6}\)|"x"|it's # not a comment""")

    def test_single_quotes_in_a_flow_list_and_double_quotes_untouched(self):
        data = self.parse("""
            include: ['src/**/*.cs', "a'b"]  # trailing comment
            """)
        self.assertEqual(data["include"], ["src/**/*.cs", "a'b"])

    def test_apostrophe_inside_a_bare_value_is_left_alone(self):
        self.assertEqual(self.parse("title: Don't edit gen-src\n")["title"], "Don't edit gen-src")


class ChecksTest(GenContractTestCase):
    def test_forbid_pattern_reports_file_and_line(self):
        self.repo.write("gen-src/A.g.cs", "// <auto-generated/>\nTODO fix\nok\n")
        self.contract("""
            - id: G1
              title: no TODOs in generated code
              why: regen erases them
              check: forbid_pattern
              scope:
                include: ["gen-src/**"]
              pattern: TODO
            """)
        rc, out, _ = self.repo.run("--quiet")
        self.assertEqual(rc, EXIT_FINDINGS)
        self.assertIn("gen-src/A.g.cs:2", out)
        self.assertIn("regen erases them", out)

    def test_first_line_in_and_require_pattern_pass_and_fail(self):
        self.repo.write("g/a.dart", "// GENERATED\npart 'a.g.dart';\n")
        self.repo.write("g/b.dart", "// hand\n")
        self.contract("""
            - id: H
              title: header
              why: w
              check: first_line_in
              scope: gen
              values: ["// GENERATED", "// GENERATED CODE"]
            - id: P
              title: part directive
              why: w
              check: require_pattern
              scope: gen
              patterns: ["^part '"]
            """, extra='filesets:\n  gen:\n    include: ["g/*.dart"]\n')
        rc, out, _ = self.repo.run("--quiet", "--json", str(self.repo.root / "f.json"))
        self.assertEqual(rc, EXIT_FINDINGS)
        found = {(f["rule"], f["file"]) for f in json.loads((self.repo.root / "f.json").read_text())["findings"]}
        self.assertEqual(found, {("H", "g/b.dart"), ("P", "g/b.dart")})

    def test_forbid_paths_passes_on_an_empty_scope(self):
        self.repo.write("gen-src/A.g.cs", "x\n")
        self.contract("""
            - id: F
              title: nothing but .cs under gen-src
              why: w
              check: forbid_paths
              scope:
                include: ["gen-src/**"]
                exclude: ["**/*.cs"]
              pattern: "."
            """)
        self.assertEqual(self.repo.run("--quiet")[0], EXIT_OK)
        self.repo.write("gen-src/README.md", "parked\n")
        rc, out, _ = self.repo.run("--quiet")
        self.assertEqual(rc, EXIT_FINDINGS)
        self.assertIn("gen-src/README.md", out)

    def test_ratchet_over_fails_and_under_suggests_lowering(self):
        self.repo.write("src/a.cs", "legacy\nlegacy\n")
        rule = """
            - id: R
              title: legacy calls only go down
              why: w
              check: ratchet
              counters:
                - name: legacy
                  scope:
                    include: ["src/**"]
                  pattern: legacy
                  unit: matches
                  max: {max}
            """
        self.contract(rule.replace("{max}", "1"))
        self.assertEqual(self.repo.run("--quiet")[0], EXIT_FINDINGS)
        self.contract(rule.replace("{max}", "5"))
        rc, out, _ = self.repo.run()
        self.assertEqual(rc, EXIT_OK)
        self.assertIn("lower the max to 2", out)

    def test_tracked_file_missing_from_disk_is_skipped(self):
        self.repo.write("gen-src/Gone.g.cs", "TODO\n")
        self.repo.write("gen-src/Here.g.cs", "fine\n")
        (self.repo.root / "gen-src/Gone.g.cs").unlink()
        self.contract("""
            - id: G
              title: t
              why: w
              check: forbid_pattern
              scope:
                include: ["gen-src/**"]
              pattern: TODO
            """)
        self.assertEqual(self.repo.run("--quiet")[0], EXIT_OK)


class SafetyTest(GenContractTestCase):
    RULE = """
        - id: G
          title: t
          why: w
          check: forbid_pattern
          scope:
            include: ["gen-src/**"]
          pattern: TODO
        """

    def test_a_scope_matching_nothing_fails(self):
        self.repo.write("src/a.cs", "x\n")
        self.contract(self.RULE)
        rc, out, _ = self.repo.run("--quiet")
        self.assertEqual(rc, EXIT_FINDINGS)
        self.assertIn("scope matches no tracked file", out)

    def test_allow_empty_opts_out(self):
        self.repo.write("src/a.cs", "x\n")
        self.contract(textwrap.dedent(self.RULE) + "  allow_empty: true\n")
        self.assertEqual(self.repo.run("--quiet")[0], EXIT_OK)

    def _waived(self, todos: int, cap: int) -> int:
        self.repo.write("gen-src/A.g.cs", "TODO\n" * todos + "ok\n")
        self.contract(textwrap.dedent(self.RULE) + f"  waived_until:\n    max: {cap}\n    until: generator 1 ships\n")
        return self.repo.run("--quiet")[0]

    def test_waiver_over_cap_fails(self):
        self.assertEqual(self._waived(3, 2), EXIT_FINDINGS)

    def test_waiver_at_or_under_cap_passes(self):
        self.assertEqual(self._waived(2, 2), EXIT_OK)

    def test_satisfied_waiver_fails_until_deleted(self):
        self.assertEqual(self._waived(0, 2), EXIT_FINDINGS)


class ContractValidationTest(GenContractTestCase):
    def assertBroken(self, rules: str, message: str, extra: str = "") -> None:
        self.repo.write("gen-src/A.g.cs", "x\n")
        self.contract(rules, extra)
        rc, _, err = self.repo.run()
        self.assertEqual(rc, EXIT_BROKEN, err)
        self.assertIn(message, err)

    def test_unknown_check(self):
        self.assertBroken("- id: A\n  title: t\n  why: w\n  check: nope\n  scope: x\n", "unknown check 'nope'")

    def test_duplicate_ids(self):
        rule = '- id: A\n  title: t\n  why: w\n  check: forbid_paths\n  scope:\n    include: ["x"]\n  pattern: "."\n'
        self.assertBroken(rule + rule, "duplicate rule id")

    def test_unknown_fileset(self):
        self.assertBroken('- id: A\n  title: t\n  why: w\n  check: forbid_paths\n  scope: missing\n  pattern: "."\n',
                          "unknown fileset `missing`")

    def test_bad_regex(self):
        self.assertBroken('- id: A\n  title: t\n  why: w\n  check: forbid_pattern\n  scope:\n    include: ["x"]\n'
                          '  pattern: "("\n', "not a valid regex")

    def test_missing_why(self):
        self.assertBroken('- id: A\n  title: t\n  check: forbid_paths\n  scope:\n    include: ["x"]\n  pattern: "."\n',
                          "missing `why`")

    def test_builtin_without_a_module(self):
        self.assertBroken("- id: A\n  title: t\n  why: w\n  check: builtin\n  name: shape\n",
                          "no `builtins:` module declared")

    def test_missing_contract(self):
        rc, _, err = self.repo.run()
        self.assertEqual(rc, EXIT_BROKEN)
        self.assertIn("no contract file", err)


class BuiltinsAndCliTest(GenContractTestCase):
    def test_project_builtin_with_a_dataclass_runs(self):
        self.repo.write("checks.py", '''
            from dataclasses import dataclass
            from specfuse.loop.gen_contract import Finding, read

            @dataclass
            class Seen:
                n: int

            def no_x(root, rule, scope, filesets, files):
                return [Finding(rule["id"], rule["severity"], p, 0, "has x")
                        for p in scope.paths if "x" in read(root, p)]

            BUILTINS = {"no_x": no_x}
            ''')
        self.repo.write("gen/a.txt", "x\n")
        self.repo.write("gen/b.txt", "y\n")
        self.contract("""
            - id: B
              title: builtin
              why: w
              check: builtin
              name: no_x
              scope:
                include: ["gen/**"]
            """, extra="builtins: checks.py\n")
        rc, out, _ = self.repo.run("--quiet")
        self.assertEqual(rc, EXIT_FINDINGS)
        self.assertIn("gen/a.txt", out)
        self.assertNotIn("gen/b.txt", out)

    def test_only_accepts_commas_and_rejects_unknown_ids(self):
        self.repo.write("gen/a.txt", "TODO\n")
        self.contract("""
            - id: A
              title: a
              why: w
              check: forbid_pattern
              scope:
                include: ["gen/**"]
              pattern: TODO
            - id: B
              title: b
              why: w
              check: forbid_pattern
              scope:
                include: ["gen/**"]
              pattern: NOPE
            """)
        self.assertEqual(self.repo.run("--quiet", "--only", "B")[0], EXIT_OK)
        self.assertEqual(self.repo.run("--quiet", "--only", "A,B")[0], EXIT_FINDINGS)
        self.assertEqual(self.repo.run("--only", "C")[0], EXIT_BROKEN)

    def test_list_and_explain(self):
        self.repo.write("gen/a.txt", "x\n")
        self.contract("""
            - id: A
              title: the title
              why: >
                folded
                why
              check: forbid_pattern
              scope:
                include: ["gen/**"]
              pattern: TODO
            """)
        rc, out, _ = self.repo.run("--list")
        self.assertEqual(rc, EXIT_OK)
        self.assertIn("A  error  the title", out)
        rc, out, _ = self.repo.run("--explain", "A")
        self.assertEqual(rc, EXIT_OK)
        self.assertIn("why      : folded why", out)


class MoreChecksTest(GenContractTestCase):
    def test_filename_first_line_and_unless_path(self):
        self.repo.write("gen-src/Good.g.cs", "// <auto-generated/>\n")
        self.repo.write("gen-src/bad.cs", "// hand\n")
        self.repo.write("src/gen-src-ish/x.json", "{}\n")
        self.contract("""
            - id: N
              title: generated files end in .g.cs
              why: w
              check: filename_matches
              scope: gen
              pattern: '\\.g\\.cs$'
            - id: H
              title: header
              why: w
              check: first_line_equals
              scope: gen
              value: "// <auto-generated/>"
            - id: P
              title: json only under docs
              why: w
              severity: warn
              check: forbid_paths
              scope:
                include: ["**"]
              pattern: '\\.json$'
              unless_path: docs/
            """, extra='filesets:\n  gen:\n    include: ["gen-src/**"]\n')
        rc, out, _ = self.repo.run("--json", str(self.repo.root / "f.json"))
        self.assertEqual(rc, EXIT_FINDINGS)
        found = {(f["rule"], f["severity"], f["file"]) for f in json.loads((self.repo.root / "f.json").read_text())["findings"]}
        self.assertEqual(found, {("N", "error", "gen-src/bad.cs"), ("H", "error", "gen-src/bad.cs"),
                                 ("P", "warn", "src/gen-src-ish/x.json")})
        self.assertIn("WARN  P", out)

    def test_ratchet_counts_files_by_default(self):
        self.repo.write("a.cs", "legacy legacy\n")
        self.repo.write("b.cs", "legacy\n")
        self.contract("""
            - id: R
              title: files with legacy calls
              why: w
              check: ratchet
              counters:
                - name: legacy-files
                  scope:
                    include: ["*.cs"]
                  pattern: legacy
                  max: 1
            """)
        rc, out, _ = self.repo.run("--quiet")
        self.assertEqual(rc, EXIT_FINDINGS)
        self.assertIn("at 2, max 1", out)

    def test_explain_a_waived_rule(self):
        self.repo.write("gen/a.txt", "TODO\n")
        self.contract("""
            - id: W
              title: t
              why: w
              check: forbid_pattern
              scope:
                include: ["gen/**"]
              pattern: TODO
              waived_until:
                max: 1
                until: the regen lands
                recorded: 2026-10-19
                reason: backlog
            """)
        rc, out, _ = self.repo.run("--explain", "W")
        self.assertEqual(rc, EXIT_OK)
        self.assertIn("WAIVED   : 1 site(s), frozen 2026-10-19", out)
        self.assertEqual(self.repo.run("--explain", "X")[0], EXIT_BROKEN)


class MoreValidationTest(ContractValidationTest):
    BASE = '- id: A\n  title: t\n  why: w\n  check: forbid_pattern\n  scope:\n    include: ["x"]\n  pattern: x\n'

    def test_bad_severity(self):
        self.assertBroken(self.BASE + "  severity: fatal\n", "severity must be one of")

    def test_check_specific_field_missing(self):
        self.assertBroken('- id: A\n  title: t\n  why: w\n  check: first_line_in\n  scope:\n    include: ["x"]\n',
                          "check `first_line_in` needs `values`")

    def test_ratchet_counter_incomplete(self):
        self.assertBroken("- id: A\n  title: t\n  why: w\n  check: ratchet\n  counters:\n    - name: c\n      max: 1\n",
                          "every ratchet counter needs `scope`")

    def test_waiver_without_until(self):
        self.assertBroken(self.BASE + "  waived_until:\n    max: 1\n", "`waived_until` needs")

    def test_builtins_module_missing_or_broken(self):
        self.assertBroken(self.BASE, "builtins module nope.py not found", extra="builtins: nope.py\n")
        self.repo.write("broken.py", "raise RuntimeError('boom')\n")
        self.assertBroken(self.BASE, "failed to import: boom", extra="builtins: broken.py\n")

    def test_version_is_required(self):
        self.repo.write("gen-contract.yml", "rules:\n  - id: A\n")
        rc, _, err = self.repo.run()
        self.assertEqual(rc, EXIT_BROKEN)
        self.assertIn("`version: 1` is required", err)


